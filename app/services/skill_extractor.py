COMPILED_SKILL_PATTERNS = [
    (skill, re.compile(pattern))
    for skill, pattern in SKILL_PATTERNS.items()
]


def extract_skills(text: str):
    if not text:
        return []

    text = text.lower()
    found = set()

    for skill, pattern in COMPILED_SKILL_PATTERNS:
        if pattern.search(text):
            found.add(skill)

    return sorted(found)
